export function chooseObjects(predictions) {
  const unique = new Map();
  for (const item of predictions) {
    if (words[item.class] && item.score >= 0.55 && !unique.has(item.class)) unique.set(item.class, item);
  }
  return [...unique.values()].sort((a, b) => b.score - a.score).slice(0, 5);
}
